#!/usr/bin/env node
// Regenerates src/queue/dictionary/topLevelDomains.generated.ts from IANA's
// root zone list. The cleanup guard never splits "word.Tld" at a full stop
// when Tld is a top-level domain, so title-case domains (example.Com,
// hops.Beer) cannot be mistaken for a missing space after a sentence.
//
// Usage: npm run generate:tlds

import { writeFile } from 'node:fs/promises';

const SOURCE_URL = 'https://data.iana.org/TLD/tlds-alpha-by-domain.txt';
const OUTPUT_PATH = new URL('../src/queue/dictionary/topLevelDomains.generated.ts', import.meta.url);

const response = await fetch(SOURCE_URL);
if (!response.ok) throw new Error(`TLD list download failed: HTTP ${response.status}`);
const lines = (await response.text()).split('\n');

const version = lines.find(line => line.startsWith('#'))?.replace(/^#\s*/, '') ?? 'unknown version';
const domains = lines
  .map(line => line.trim().toLowerCase())
  .filter(line => /^[a-z]+$/.test(line))
  .sort();

const output = [
  '// GENERATED by scripts/generate-top-level-domains.mjs. Do not edit by hand.',
  `// Source: ${SOURCE_URL} (${version}). Internationalized (xn--) domains are`,
  '// omitted: they cannot match a plain word.',
  '',
  `export const TOP_LEVEL_DOMAINS: ReadonlySet<string> = new Set(${JSON.stringify(domains.join(' '))}.split(' '));`,
  '',
].join('\n');

await writeFile(OUTPUT_PATH, output);
console.log(`Wrote ${domains.length} top-level domains to ${OUTPUT_PATH.pathname}`);
