#!/usr/bin/env node
// Regenerates src/queue/dictionary/englishWords.generated.ts from SCOWL/ESDB.
// The licence requires its notice to travel with every copy of the list, so
// the header returned by the generator is preserved verbatim in the output.
//
// Usage: npm run generate:dictionary

import { writeFile } from 'node:fs/promises';

const SOURCE_URL =
  'http://app.aspell.net/create?max_size=50&spelling=US&spelling=GBs&max_variant=1' +
  '&diacritic=both&special=hacker&special=roman-numerals&download=wordlist&encoding=utf-8&format=inline';
const OUTPUT_PATH = new URL('../src/queue/dictionary/englishWords.generated.ts', import.meta.url);

const response = await fetch(SOURCE_URL);
if (!response.ok) throw new Error(`Word list download failed: HTTP ${response.status}`);
const text = await response.text();

const separator = text.indexOf('\n---\n');
if (separator === -1) throw new Error('Word list is missing its licence header separator');

const header = text.slice(0, separator).trimEnd();
const words = [...new Set(
  text.slice(separator + 5).split('\n').map(word => word.trim().toLowerCase()).filter(Boolean),
)].sort();

const output = [
  '// GENERATED by scripts/generate-dictionary.mjs. Do not edit by hand.',
  '/*',
  ...header.split('\n').map(line => ` * ${line}`.trimEnd()),
  ' */',
  '',
  `export const ENGLISH_WORDS = ${JSON.stringify(words.join('\n'))};`,
  '',
].join('\n');

await writeFile(OUTPUT_PATH, output);
console.log(`Wrote ${words.length} words to ${OUTPUT_PATH.pathname}`);
