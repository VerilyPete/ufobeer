#!/usr/bin/env node
// Regenerates src/queue/dictionary/spellingCorrections.generated.ts: the only
// spelling fixes the cleanup guard will accept from the model.
//
// Source pairs come from codespell's dictionary (CC BY-SA 3.0, derived from
// English Wikipedia). A pair is kept only when both sides are plain lowercase
// ASCII, the correction is unambiguous, the misspelling is NOT a word in
// SCOWL/ESDB size 95 (so no real word can ever be "corrected"), and the
// correction IS a word there.
//
// Usage: npm run generate:spelling

import { writeFile } from 'node:fs/promises';

const CODESPELL_URL =
  'https://raw.githubusercontent.com/codespell-project/codespell/main/codespell_lib/data/dictionary.txt';
const SCOWL_URL =
  'http://app.aspell.net/create?max_size=95&spelling=US&spelling=GBs&spelling=GBz&spelling=CA&spelling=AU' +
  '&max_variant=3&diacritic=both&special=hacker&special=roman-numerals&download=wordlist&encoding=utf-8&format=inline';
const OUTPUT_PATH = new URL('../src/queue/dictionary/spellingCorrections.generated.ts', import.meta.url);
const PLAIN_WORD = /^[a-z]+$/;

async function download(url) {
  const response = await fetch(url);
  if (!response.ok) throw new Error(`Download failed: HTTP ${response.status} for ${url}`);
  return response.text();
}

const [codespell, scowl] = await Promise.all([download(CODESPELL_URL), download(SCOWL_URL)]);

const separator = scowl.indexOf('\n---\n');
if (separator === -1) throw new Error('SCOWL list is missing its header separator');
const realWords = new Set(scowl.slice(separator + 5).split('\n').map(word => word.trim().toLowerCase()));

const pairs = codespell
  .split('\n')
  .map(line => line.trim().match(/^([^-]+)->(.+)$/))
  .filter(match => match !== null)
  .map(([, misspelling, correction]) => [misspelling, correction.replace(/,$/, '')])
  .filter(([misspelling, correction]) =>
    PLAIN_WORD.test(misspelling) && PLAIN_WORD.test(correction) &&
    !realWords.has(misspelling) && realWords.has(correction))
  .sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0));

const output = [
  '// GENERATED by scripts/generate-spelling-corrections.mjs. Do not edit by hand.',
  '/*',
  ' * Misspelling -> correction pairs adapted from codespell\'s dictionary.txt',
  ' * (https://github.com/codespell-project/codespell), a derivative work of',
  ' * English Wikipedia, licensed under the Creative Commons',
  ' * Attribution-ShareAlike 3.0 License',
  ' * (https://creativecommons.org/licenses/by-sa/3.0/). This adapted list is',
  ' * released under the same licence.',
  ' *',
  ' * Changes: kept only unambiguous lowercase ASCII pairs whose misspelling is',
  ' * not, and whose correction is, a word in SCOWL/ESDB size 95',
  ' * (https://wordlist.aspell.net, Copyright 2000-2026 by Kevin Atkinson).',
  ' * Format: one "misspelling correction" pair per line.',
  ' */',
  '',
  `export const SPELLING_CORRECTIONS = ${JSON.stringify(pairs.map(pair => pair.join(' ')).join('\n'))};`,
  '',
].join('\n');

await writeFile(OUTPUT_PATH, output);
console.log(`Wrote ${pairs.length} pairs to ${OUTPUT_PATH.pathname}`);
